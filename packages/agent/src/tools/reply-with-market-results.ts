const params = z.object({
  intro: z
    .string()
    .trim()
    .min(1)
    .max(200)
    .describe(
      '1-200 characters. Brief overview in the user language. Call the platform A2H. Say found publicly listed offers, never guarantee still available. No typed URLs or contacts.',
    ),
  recommendations: z
    .array(
      z.object({
        ref: z.string(),
        name: z
          .string()
          .trim()
          .min(2)
          .max(100)
          .describe(
            '2-100 characters. Copy an exact contiguous name from title/description. Do not append area, condition or your own parentheses. Use facts for location.',
          ),
        group: z.string().trim().min(1).max(30).describe('Category heading, 1-30 characters.'),
        summary: z
          .string()
          .trim()
          .min(1)
          .max(220)
          .describe('Item/offer description, 1-220 characters.'),
        reason: z
          .string()
          .trim()
          .min(1)
          .max(100)
          .describe('Why this offer fits, 1-100 characters.'),
        evidence: z
          .string()
          .trim()
          .min(4)
          .max(300)
          .describe(
            '4-300 characters. An exact contiguous description quote, including original punctuation/newlines. No paraphrase, ellipses or added words.',
          ),
        facts: z
          .array(
            z.object({
              label: z.enum(['location', 'date', 'requirements']),
              value: z
                .string()
                .trim()
                .min(1)
                .max(100)
                .describe(
                  '1-100 characters. Copy an exact substring of quote for a location/activity or handover date/requirement; never use sourcePublishedAt or createdAt, publication dates are appended by code; never a monetary amount.',
                ),
              quote: z
                .string()
                .trim()
                .min(4)
                .max(300)
                .describe(
                  '4-300 characters. Exact contiguous text from this listing description. Copy, do not translate or reformat it.',
                ),
            }),
          )
          .max(3)
          .describe('0-3 facts; use [] when details are uncertain. All fields are required.'),
      }),
    )
    .min(1)
    .max(6),
});
const singleLine = (s: string) => s.replace(/[\r\n]+/g, ' ').trim();
function validateSelections(
  ctx: MatchContext,
  args: z.infer<typeof params>,
  canRecover = true,
): MarketCandidate[] | Extract<DraftResult, { error: string }> {
  const selected: MarketCandidate[] = [];
  const publicFields = [
    args.intro,
    ...args.recommendations.flatMap((item) => [
      item.name,
      item.group,
      item.summary,
      item.reason,
      ...item.facts.map((f) => f.value),
    ]),
  ];
  if (publicFields.some((text) => redactMarketText(text) !== text || /https?:|www\./i.test(text)))
    return {
      error:
        'invalid recommendation: omit contacts and typed URLs; source links are generated by the tool',
    };
  const errors: string[] = [];
  for (const [index, item] of args.recommendations.entries()) {
    const path = `recommendations.${index}`;
    if (
      !ctx.marketPlan &&
      /[£€¥$]\s*\d|\d+\s*(?:英镑|镑|元)|符合预算|预算内|within (?:your )?budget/i.test(
        [item.summary, item.reason, ...item.facts.map((f) => f.value)].join(' '),
      )
    )
      errors.push(
        `${path}.summary/reason/facts: remove monetary amounts and budget claims; the tool appends the listing own post-level price`,
      );
    const listing = ctx.marketListings?.find((n) => n.ref === item.ref);
    if (!listing || selected.some((n) => n.id === listing.id)) {
      errors.push(`${path}.ref: use distinct refs returned by market_search`);
      continue;
    }
    if (ctx.marketPlan) {
      const assessment = assessMarketListing(listing, ctx.marketPlan, item.name);
      if (!assessment.needs.length)
        errors.push(`${path}.ref: this is not an offer for the requested core need`);
      for (const criterion of ['area', 'route']) {
        if (
          !assessment.checks.some(
            (check) => check.label === criterion && check.status === 'unknown',
          )
        )
          continue;
        const alternatives = (ctx.marketListings ?? []).filter((candidate) => {
          const other = assessMarketListing(candidate, ctx.marketPlan!);
          return (
            candidate.id !== listing.id &&
            other.needs.some((id) => assessment.needs.includes(id)) &&
            !other.checks.some((check) => check.status === 'mismatch') &&
            other.checks.some((check) => check.label === criterion && check.status === 'met')
          );
        });
        const hasSelectedConfirmed = args.recommendations.some((selection) => {
          const candidate = ctx.marketListings?.find((n) => n.ref === selection.ref);
          if (!candidate || candidate.id === listing.id) return false;
          const checked = assessMarketListing(candidate, ctx.marketPlan!, selection.name);
          return (
            !checked.checks.some((check) => check.status === 'mismatch') &&
            checked.needs.some((id) => assessment.needs.includes(id)) &&
            checked.checks.some((check) => check.label === criterion && check.status === 'met')
          );
        });
        if (alternatives.length && !hasSelectedConfirmed)
          errors.push(
            `${path}.ref: prefer confirmed ${criterion} before unknown ${criterion}; usable refs: ${alternatives
              .slice(0, 6)
              .map((candidate) => candidate.ref)
              .join(',')}`,
          );
      }
      const wrong = assessment.checks.filter((check) => check.status === 'mismatch');
      if (wrong.length)
        errors.push(
          `${path}.ref: conflicts with hard requirements (${wrong.map((check) => check.label).join(',')}); choose a met or explicitly unknown candidate, not this one`,
        );
    }
    if (
      !isActiveMarketListing(listing, new Date(), { respectAvailability: !ctx.marketPlan }) ||
      !hasLondonEvidence(listing)
    )
      errors.push(`${path}.ref: listing ended or lacks London evidence`);
    if (ctx.marketTarget && ctx.marketTarget !== 'ANY' && listing.tradeType !== ctx.marketTarget)
      errors.push(`${path}.ref: listing is on the wrong counterpart side`);
    if (!(listing.title + '\n' + listing.description).includes(item.name))
      errors.push(
        `${path}.name: copy a literal source name; do not translate or append labels. Available exact names: ${JSON.stringify(
          listing.description
            .split('\n')
            .filter((line) => /^\s*- /.test(line))
            .map((line) =>
              line
                .replace(/^\s*- /, '')
                .split('｜')[0]
                ?.trim(),
            )
            .filter((name) => name && name.length >= 2 && name.length <= 100)
            .slice(0, 6),
        )}. Or use the exact title ${JSON.stringify(listing.title)}`,
      );
    if (!listing.description.includes(item.evidence))
      errors.push(
        `${path}.evidence: copy an exact contiguous description quote, preserving punctuation/newlines; use a shorter quote`,
      );
    for (const [factIndex, fact] of (ctx.marketPlan ? [] : item.facts).entries()) {
      const factPath = `${path}.facts.${factIndex}`;
      if (!listing.description.includes(fact.quote))
        errors.push(
          `${factPath}.quote: must be an exact contiguous substring of this listing description`,
        );
      if (!fact.quote.includes(fact.value))
        errors.push(
          `${factPath}.value: must be a literal substring of its quote; omit uncertain facts${fact.label === 'date' ? '; do not put sourcePublishedAt/createdAt in facts: original publication date is already appended automatically, date facts are only activity/trip/handover dates written in description' : ''}`,
        );
    }
    selected.push(listing);
  }
  if (errors.length) {
    // P20 真实 Telegram 回归：最后一次只保留独立通过全部检查的条目，
    // 不让一条改写名称拖掉其他有效结果；重新核对候选间的地点/路线优先规则。
    if (
      canRecover &&
      ctx.marketPlan &&
      ctx.outboundInputFailures?.tool === 'reply_with_market_results' &&
      ctx.outboundInputFailures.count === 2
    ) {
      const valid = args.recommendations.filter(
        (_, index) => !errors.some((error) => error.startsWith(`recommendations.${index}.`)),
      );
      if (valid.length) return validateSelections(ctx, { ...args, recommendations: valid }, false);
    }
    return {
      error: `invalid recommendation: correct ALL listed fields in one repair, preserving valid entries. ${errors.join('; ')}`,
    };
  }

  const followup = requestFocusedFollowup(ctx, args, selected);
  if (followup) return { error: followup, kind: 'research_required' };
  return selected;
}
function requestFocusedFollowup(
  ctx: MatchContext,
  args: z.infer<typeof params>,
  selected: MarketCandidate[],
): string | null {
  const queries = ctx.marketQueries ?? [];
  if (
    !ctx.marketPlan ||
    !queries.length ||
    !ctx.marketDetailIds?.length ||
    queries.length >= 8 ||
    queries.some((q) => q.purpose === 'enrich')
  )
    return null;
  const choices = buildMarketChoices({
    candidates: selected,
    plan: ctx.marketPlan,
    names: Object.fromEntries(args.recommendations.map((item) => [item.ref, item.name])),
  });
  const task = buildMarketResearchTasks({
    choices,
    plan: ctx.marketPlan,
    detailIds: ctx.marketDetailIds,
    queries: queries.map((q) => q.keyword),
    remainingDetails: 8 - ctx.marketDetailIds.length,
    remainingQueries: 8 - queries.length,
  }).find((step) => step.action === 'search');
  if (!task) return null;
  const search = {
    plan: null,
    intent: ctx.marketPlan.intent,
    purpose: 'enrich',
    queries: [
      {
        keyword: task.keyword,
        entity: task.entity,
        page: 1,
        tradeType: ctx.marketTarget ?? (ctx.marketPlan.intent === 'companion' ? 'PEER' : 'SELL'),
      },
    ],
  };
  return `research incomplete: do one focused market_search before replying: ${JSON.stringify(search)}. It targets ${task.missing.join('/')}; never borrow another owner's facts. Then reply even if still unknown, using backups. Do not repeat broad discovery.`;
}
function renderListings(p: {
  args: z.infer<typeof params>;
  listings: MarketCandidate[];
  zh: boolean;
  ctx: MatchContext;
}): string {
  const blocks: string[] = [];
  let group = '';
  for (const [index, item] of p.args.recommendations.entries()) {
    const listing = p.listings[index]!;
    const assessment = p.ctx.marketPlan
      ? assessMarketListing(listing, p.ctx.marketPlan, item.name)
      : null;
    const conditionLabels: Record<string, string> = {
      area: '地点',
      budget:
        listing.tradeType === 'BUY'
          ? '买家预算/报价'
          : p.ctx.marketPlan?.intent === 'housing'
            ? '租金/计价单位'
            : '价格/计价单位',
      route: '路线',
      date: '日期/年份',
      date_conflict: '原文行程与可用期冲突',
      required: '必要条件',
      excluded: '排除条件',
      availability: '可用状态',
      skill: '活动水平',
    };
    const unknown =
      assessment?.checks
        .filter((check) => check.status === 'unknown')
        .map((check) =>
          check.label.startsWith('preference:')
            ? check.label.slice('preference:'.length)
            : p.zh
              ? (conditionLabels[check.label] ?? check.label)
              : check.label,
        ) ?? [];
    const uncertain = unknown.length
      ? `${p.zh ? '待确认：' : 'Unconfirmed: '}${unknown.join(' / ')}`
      : '';
    const itemPrice = assessment?.itemPriceEvidence
      ? `${p.zh ? (listing.tradeType === 'BUY' ? '买家报价依据：' : p.ctx.marketPlan?.intent === 'housing' ? '租金依据：' : '单品报价依据：') : 'Item price evidence: '}${singleLine([...assessment.itemPriceEvidence].slice(0, 140).join(''))}${[...assessment.itemPriceEvidence].length > 140 ? '…' : ''}`
      : '';
    if (item.group !== group) {
      group = item.group;
      blocks.push(`【${singleLine(group)}】`);
    }
    const facts = (p.ctx.marketPlan ? [] : item.facts)
      .map(
        (f) =>
          `${p.zh ? { location: '地点', date: '时间', requirements: '要求' }[f.label] : { location: 'Location', date: 'When', requirements: 'Requirements' }[f.label]}${p.zh ? '：' : ': '}${singleLine(f.value)}`,
      )
      .join(' | ');
    const price = p.zh
      ? listing.priceLabel
      : listing.priceLabel
          .replace('帖内报价范围：', 'Post price range: ')
          .replace('帖子标价：', 'Post price: ')
          .replace('帖子未标价', 'Not priced')
          .replace('单品价格需确认', 'Confirm individual item price')
          .replace('具体对象/计价单位请确认', 'Confirm item and unit');
    const stamp = listing.isRepost
      ? listing.sourcePublishedAt
        ? `${p.zh ? '原帖发布' : 'Original posted'} ${listing.sourcePublishedAt.slice(0, 10)}`
        : p.zh
          ? '原帖时间未确认'
          : 'Original date unconfirmed'
      : listing.createdAt
        ? `${p.zh ? '发布' : 'Posted'} ${listing.createdAt.slice(0, 10)}`
        : '';
    const links =
      `[${p.zh ? 'A2H详情' : 'A2H listing'}](${listing.url})` +
      (listing.sourceUrl
        ? ` · [${p.zh ? '小红书原帖' : 'Original post'}](${listing.sourceUrl})`
        : '');
    blocks.push(
      [
        `${index + 1}. ${singleLine(item.name)}`,
        singleLine(p.ctx.marketPlan ? item.evidence : item.summary),
        `${p.zh ? '适合：' : 'Why: '}${p.ctx.marketPlan ? (p.zh ? '主体需求相符；条件核对见下方。' : 'Matches the core need; see checked conditions below.') : singleLine(item.reason)}`,
        ...(assessment?.checks
          .filter(
            (check) =>
              check.status === 'met' &&
              ['area', 'route', 'date'].includes(check.label) &&
              check.evidence,
          )
          .map(
            (check) =>
              `${p.zh ? (conditionLabels[check.label] ?? check.label) : check.label}${p.zh ? '依据：' : ' evidence: '}${singleLine(check.evidence!)}`,
          ) ?? []),
        facts,
        itemPrice,
        uncertain,
        ...(listing.tradeType === 'PEER' && listing.priceLabel === '帖子未标价' ? [] : [price]),
        `${listing.tradeType === 'PEER' ? (p.zh ? '搭伴帖' : 'Companion post') : listing.tradeType === 'SELL' ? (p.zh ? '供给帖' : 'Offer') : p.zh ? '求购/求助帖' : 'Wanted/request'} · ${stamp}`,
        `${p.zh ? '来源：' : 'Source: '}${links}`,
      ]
        .filter(Boolean)
        .join('\n'),
    );
  }
  return blocks.join('\n\n');
}
export function replyWithMarketResultsTool(deps: AgentDeps) {
  return makeOutboundTool(deps, {
    name: 'reply_with_market_results',
    description:
      'SENDS a grouped recommendation of 1-6 specific London A2H listings matching second-hand, housing, carry-on help or companion requests. Explain the actual item/room/route/activity and why it fits, not the post. With an adaptive plan, the tool sorts 1-3 evidenced priorities and up to 2 backups (or 3 leads when none is confirmed), deduplicates identical original posts, and explains budget/area/route/time fit from source checks. The final description uses ONLY your exact evidence quote, and fit/location/route/price come from code assessments; free summary/reason/facts are ignored. Choose an informative contiguous quote about this specific offer. Keep different owners/rooms/offers separate. Use market_enrich for selected refs first. The tool adds each listing own post-level price, original date and public links. Do not type monetary amounts or budget-fit claims in summary, reason or facts; prices are appended from structured source fields. Never assign a bundle price range to one item, claim a listing is within budget without item-level price evidence, invent contact details, publish or arrange a transaction. Reposts must be confirmed through their original link.',
    parameters: params,
    toDraft: async (ctx, args: z.infer<typeof params>) => {
      const selected = validateSelections(ctx, args);
      if ('error' in selected) return Promise.resolve(selected);
      const intro = singleLine(args.intro);
      const zh = ctx.demand?.lang ? ctx.demand.lang === 'zh' : /\p{Script=Han}/u.test(intro);
      const presentation = ctx.marketPlan
        ? renderMarketChoiceReply({
            listings: selected,
            selections: args.recommendations,
            plan: ctx.marketPlan,
            zh,
          })
        : null;
      const rendered = presentation
        ? [...presentation.choices.primary, ...presentation.choices.backup].map(
            (row) => row.listing,
          )
        : selected;
      const text = (
        presentation?.text ?? `${intro}\n\n${renderListings({ args, listings: selected, zh, ctx })}`
      ).replaceAll('有闲', 'A2H');
      if (presentation)
        await deps.repos.traces.create({
          kind: 'gate',
          inputRef: ctx.sourceMessageId,
          phase: ctx.phase,
          latencyMs: 0,
          costMicro: 0,
          output: {
            gate: 'market_recommendation_selection',
            decision: 'selected',
            rejectedRefs: args.recommendations
              .filter((item) => !selected.some((listing) => listing.ref === item.ref))
              .map((item) => item.ref),
            primaryRefs: presentation.choices.primary.map((row) => row.listing.ref),
            backupRefs: presentation.choices.backup.map((row) => row.listing.ref),
            omittedRefs: selected.filter((n) => !rendered.includes(n)).map((n) => n.ref),
          },
        });
      if (text.length > 3700)
        return Promise.resolve({
          error:
            'invalid recommendation: reply too long; shorten descriptions or choose fewer listings',
        });
      return Promise.resolve({
        kind: 'recommendation' as const,
        target: ctx.chatId,
        text,
        supplierSummaries: rendered.map((n) =>
          JSON.stringify({
            ...marketListingForModel(
              n,
              500,
              ctx.marketPlan?.needs.flatMap((need) => need.terms) ?? [],
            ),
            selectedName: args.recommendations.find((item) => item.ref === n.ref)?.name,
            selectedEvidence: args.recommendations.find((item) => item.ref === n.ref)?.evidence,
            selectedFacts: ctx.marketPlan
              ? []
              : args.recommendations.find((item) => item.ref === n.ref)?.facts,
          }),
        ),
        ...(ctx.marketPlan ? { evaluationDemand: buildEvaluationDemand(ctx.marketPlan, zh) } : {}),
        inputRef: ctx.sourceMessageId,
        ...groupReplyAddressing(ctx),
      });
    },
  });
}

/** P20: 建档失败时仍按本轮经原请求约束的计划评估，不能携带上一条需求或预算。 */
function buildEvaluationDemand(plan: MarketPlan, zh: boolean): DemandDraft {
  const route = plan.route ? `${plan.route.from[0] ?? ''} → ${plan.route.to[0] ?? ''}` : '';
  return {
    category:
      plan.intent === 'second_hand'
        ? 'second_hand'
        : plan.intent === 'housing'
          ? 'housing'
          : 'other',
    confidence: 1,
    need: [...plan.needs.map((need) => need.terms[0] ?? need.id), ...(route ? [route] : [])]
      .join(' / ')
      .slice(0, 80),
    lang: zh ? 'zh' : 'en',
    ...(plan.budget !== undefined ? { budgetPence: Math.round(plan.budget * 100) } : {}),
    ...(plan.dateRange ? { whenText: `${plan.dateRange.from} to ${plan.dateRange.to}` } : {}),
    ...(plan.requiredArea?.length
      ? { fromPostcode: plan.requiredArea.join(' / ').slice(0, 20) }
      : {}),
  };
}
